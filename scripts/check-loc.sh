#!/usr/bin/env bash
# uq-loc 1.0.0: fails when a source file has more than 400 lines of code.
#
#   scripts/check-loc.sh            check every tracked source file (CI)
#   scripts/check-loc.sh FILE...    check only these files
#   scripts/check-loc.sh --top N    list the N largest files, then check
#
# A line of code is a line that is not blank and not only a comment. Comments are `//`, `/* */`
# (Rust, C, C++, QML, JS, TS, Go, Java), `#` (shell, Python, CMake, Ruby, Perl; not `#[` attributes
# or C preprocessor lines), `--` and `--[[ ]]` (Lua), and a Python docstring standing on its own.
# Files without an extension are checked when their first line is a shell or Python `#!`.
#
# Not checked: generated files (`@generated`, `do not edit` or `generated by` in the first five
# lines), the uQ kits the repo vendors (every file listed in uq/native.toml), anything under
# vendor/, third_party/, node_modules/ or fixtures/, *.min.js, and the paths matched by the
# globs in uq/loc-ignore (one per line, `#` comments; for generated or data files only, never to
# let a hand-written file stay long). LOC_MAX overrides the limit.
#
# Part of uQ's kits (uQ's native/README.md): copy it unchanged to scripts/check-loc.sh and list it
# in uq/native.toml under [uq-loc] so check-uq-native.sh keeps it current. Exit 0 when every file
# is within the limit, 1 when one is not, 2 on bad usage.
set -u
max=${LOC_MAX:-400}
top=0
if [ "${1:-}" = --top ]; then
    [[ ${2:-} =~ ^[0-9]+$ ]] || { echo "usage: check-loc.sh [--top N] [FILE...]" >&2; exit 2; }
    top=$2; shift 2
fi

# Paths not to check: vendored kits and the repo's own ignore globs.
declare -A VENDORED=()
if [ -r uq/native.toml ]; then
    while read -r f; do [ -n "$f" ] && VENDORED[$f]=1; done < <(
        awk '/^[[:space:]]*files[[:space:]]*=/ { sub(/^[^=]*=/, ""); gsub(/[][",]/, " "); n = split($0, a, " "); for (i = 1; i <= n; i++) print a[i] }' uq/native.toml)
fi
ignores=()
if [ -r uq/loc-ignore ]; then
    while IFS= read -r g; do
        g=${g%%#*}; g=${g%"${g##*[![:space:]]}"}; g=${g#"${g%%[![:space:]]*}"}
        [ -n "$g" ] && ignores+=("$g")
    done < uq/loc-ignore
fi

# Comment style for a path: slash, hash, lua, or nothing (not a source file).
style() {
    case $1 in
        *.min.js) return ;;
        *.rs|*.c|*.cc|*.cpp|*.cxx|*.h|*.hh|*.hpp|*.hxx|*.qml|*.js|*.mjs|*.cjs|*.ts|*.tsx|*.jsx|*.go|*.java|*.kt|*.swift) echo slash ;;
        *.py|*.sh|*.bash|*.zsh|*.pl|*.rb|*.cmake|*/CMakeLists.txt|CMakeLists.txt|*/PKGBUILD|PKGBUILD) echo hash ;;
        *.lua) echo lua ;;
        */*.*|*.*) ;;
        *) head -n 1 "$1" 2>/dev/null | grep -qE '^#!.*(sh|bash|python[0-9.]*)([[:space:]]|$)' && echo hash ;;
    esac
}

skipped() {
    local f=$1 g
    [ -n "${VENDORED[$f]:-}" ] && return 0
    case /$f in */vendor/*|*/third_party/*|*/node_modules/*|*/fixtures/*) return 0 ;; esac
    for g in "${ignores[@]}"; do
        # shellcheck disable=SC2053
        [[ $f == $g ]] && return 0
    done
    head -n 5 "$f" 2>/dev/null | grep -qiE '@generated|do not edit|generated by' && return 0
    return 1
}

count() {
    awk -v style="$1" '
        function code() { n++ }
        {
            s = $0; sub(/^[ \t]+/, "", s); sub(/[ \t\r]+$/, "", s)
            if (inblock) {
                if (index(s, close_tok)) {
                    inblock = 0; rest = substr(s, index(s, close_tok) + length(close_tok))
                    sub(/^[ \t]+/, "", rest)
                    if (rest != "" && rest !~ /^\/\//) code()
                }
                next
            }
            if (s == "") next
            if (style == "slash") {
                if (s ~ /^\/\//) next
                if (s ~ /^\/\*/) {
                    rest = substr(s, 3)
                    if (index(rest, "*/")) {
                        rest = substr(rest, index(rest, "*/") + 2); sub(/^[ \t]+/, "", rest)
                        if (rest != "" && rest !~ /^\/\//) code()
                    } else { inblock = 1; close_tok = "*/" }
                    next
                }
            } else if (style == "hash") {
                if (NR == 1 && s ~ /^#!/) next
                if (s ~ /^#/) next
                if (s ~ /^("""|'\'''\'''\'')/) {
                    q = substr(s, 1, 3); rest = substr(s, 4)
                    if (!index(rest, q)) { inblock = 1; close_tok = q }
                    next
                }
            } else if (style == "lua") {
                if (s ~ /^--\[=*\[/) {
                    if (!index(s, "]]")) { inblock = 1; close_tok = "]]" }
                    next
                }
                if (s ~ /^--/) next
            }
            code()
        }
        END { print n + 0 }
    ' "$2"
}

if [ $# -gt 0 ]; then
    files=("$@")
else
    mapfile -t files < <(git ls-files)
fi

status=0
checked=0
results=()
for f in "${files[@]}"; do
    [ -f "$f" ] && [ ! -L "$f" ] || continue
    st=$(style "$f")
    [ -n "$st" ] || continue
    skipped "$f" && continue
    n=$(count "$st" "$f")
    checked=$((checked + 1))
    results+=("$n $f")
    if [ "$n" -gt "$max" ]; then
        echo "check-loc: $f has $n lines of code (limit $max); split it into smaller modules" >&2
        status=1
    fi
done
if [ "$top" -gt 0 ] && [ ${#results[@]} -gt 0 ]; then
    printf '%s\n' "${results[@]}" | sort -rn | head -n "$top"
fi
if [ $status = 0 ]; then
    echo "check-loc: $checked files, all within $max lines of code"
fi
exit $status
