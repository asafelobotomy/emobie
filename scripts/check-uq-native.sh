declare -A KIT_DIR=([uq-theme]=native/uq-theme [uq-diag]=native/uq-diag [uq-consts]=native/uq-consts [uq-tokens]=web/uq-tokens)
declare -A KIT_HEAD=([uq-theme]=uq_theme.rs [uq-diag]=uq_diag.rs [uq-consts]=uq_consts.rs [uq-tokens]=uq-tokens.js)

sync=""
if [ "${1:-}" = --sync ]; then
    [ $# -ge 2 ] && [ -d "$2/native" ] || { echo "usage: check-uq-native.sh --sync UQ_DIR [uq/native.toml]" >&2; exit 2; }
    sync=$2; shift 2
fi
manifest=${1:-uq/native.toml}
[ -r "$manifest" ] || { echo "check-uq-native: cannot read $manifest" >&2; exit 2; }

# "kit<TAB>key<TAB>value" for each `key = value` line, lists flattened to space-separated words.
entries() {
    awk '
        /^[[:space:]]*(#|$)/ { next }
        /^\[[a-z0-9-]+\][[:space:]]*$/ { kit = $0; gsub(/[][[:space:]]/, "", kit); next }
        /^[a-z_]+[[:space:]]*=/ {
            key = $0; sub(/[[:space:]]*=.*/, "", key)
            val = $0; sub(/^[^=]*=[[:space:]]*/, "", val); sub(/[[:space:]]+#.*$/, "", val)
            gsub(/[][",]/, " ", val); gsub(/[[:space:]]+/, " ", val); sub(/^ /, "", val); sub(/ $/, "", val)
            print kit "\t" key "\t" val; next
        }
        { print "?\tbad\t" $0 }
    ' "$manifest"
}

status=0
fail() { echo "check-uq-native: $*" >&2; status=1; }
declare -A VERSION FILES CODES SOURCES
while IFS=$'\t' read -r kit key val; do
    if [ "$kit" = "?" ] || [ -z "$kit" ]; then fail "$manifest: can't read: $val"; continue; fi
    [ -n "${KIT_DIR[$kit]:-}" ] || { fail "$manifest: unknown kit [$kit]"; continue; }
    case $key in
        version) VERSION[$kit]=$val ;;
        files) FILES[$kit]=$val ;;
        codes) CODES[$kit]=$val ;;
        sources) SOURCES[$kit]=$val ;;
        *) fail "$manifest: [$kit] has an unknown key $key" ;;
    esac
done < <(entries)

if [ -n "$sync" ]; then
    for kit in "${!FILES[@]}"; do
        dir=$sync/${KIT_DIR[$kit]}
        for file in ${FILES[$kit]}; do
            src=$dir/$(basename "$file")
            [ -r "$src" ] || { fail "--sync: uQ has no $src"; continue; }
            cp "$src" "$file"
        done
        new=$(head -n 5 "$dir/${KIT_HEAD[$kit]}" | grep -m1 -oE "$kit [0-9]+\.[0-9]+\.[0-9]+" | cut -d' ' -f2)
        if [ -n "$new" ] && [ "$new" != "${VERSION[$kit]:-}" ]; then
            sed -i "/^\[$kit\]/,/^\[/ s/^version *=.*/version = \"$new\"/" "$manifest"
            echo "check-uq-native: $kit ${VERSION[$kit]:-?} -> $new"
            VERSION[$kit]=$new
        fi
    done
    me=$(dirname "$0")/check-uq-native.sh
    # sha256sum, not cmp: a bare Arch container has coreutils but not diffutils
    if [ -r "$sync/native/check-uq-native.sh" ] &&
        [ "$(sha256sum < "$sync/native/check-uq-native.sh")" != "$(sha256sum < "$me")" ]; then
        cp "$sync/native/check-uq-native.sh" "$me"
        echo "check-uq-native: updated $me; run it again" >&2
        exit 1
    fi
fi

for kit in "${!FILES[@]}"; do
    pinned=${VERSION[$kit]:-}
    [[ $pinned =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { fail "[$kit] needs version = \"X.Y.Z\""; continue; }
    for file in ${FILES[$kit]}; do
        name=$(basename "$file")
        [ -r "$file" ] || { fail "cannot read $file"; continue; }
        found=$(head -n 5 "$file" | grep -m1 -oE "$kit [0-9]+\.[0-9]+\.[0-9]+" | cut -d' ' -f2)
        if [ "$found" != "$pinned" ]; then
            fail "$file is $kit ${found:-?}, pinned $pinned"; continue
        fi
        want=${SUMS[$kit/$pinned/$name]:-}
        have=$(sha256sum "$file" | cut -d' ' -f1)
        if [ -z "$want" ]; then
            fail "this script does not know $kit $pinned $name; copy the newer one from uQ (native/check-uq-native.sh)"
        elif [ "$want" != "$have" ]; then
            fail "$file was edited (it is not $kit $pinned's $name); copy it again from uQ"
        else
            echo "check-uq-native: $file is $kit $found"
        fi
    done
done
for kit in "${!VERSION[@]}"; do
    [ -n "${FILES[$kit]:-}" ] || fail "[$kit] lists no files"
done

# uq-diag: the codes the sources log and the app's list agree.
check_codes() {
    local list=$1; shift
    local prefix used listed live dups unknown unused n bad=0
    [ -r "$list" ] || { fail "cannot read $list"; return; }
    prefix=$(grep -m1 -oE '^id *= *"[A-Z0-9]+-' "$list" | sed -E 's/.*"//; s/-$//')
    [ -n "$prefix" ] || { fail "no codes in $list"; return; }
    used=$(grep -rhoE "\[$prefix-[0-9]{3}\]" --exclude='uq_diag.rs' --exclude='uqdiag.*' "$@" | tr -d '[]' | sort -u)
    read_list() {
        awk -v want="$1" '
            /^\[\[code\]\]/ { if (id != "") emit(); id = ""; retired = 0; next }
            /^id *=/ { id = $0; sub(/^id *= *"/, "", id); sub(/".*/, "", id) }
            /^retired *= *true/ { retired = 1 }
            function emit() { if (want == "all" || !retired) print id }
            END { if (id != "") emit() }
        ' "$list" | sort
    }
    listed=$(read_list all)
    live=$(read_list live)
    dups=$(printf '%s\n' "$listed" | uniq -d)
    [ -z "$dups" ] || { fail "listed twice in $list: $dups"; bad=1; }
    unknown=$(comm -23 <(printf '%s\n' "$used") <(printf '%s\n' "$listed" | sort -u) | grep . || true)
    [ -z "$unknown" ] || { fail "logged but not in $list: ${unknown//$'\n'/ }"; bad=1; }
    unused=$(comm -13 <(printf '%s\n' "$used") <(printf '%s\n' "$live" | sort -u) | grep . || true)
    [ -z "$unused" ] || { fail "listed in $list but nothing logs them (set retired = true): ${unused//$'\n'/ }"; bad=1; }
    for k in severity title means fix; do
        n=$(grep -cE "^$k *= *\"[^\"]+\"" "$list" || true)
        [ "$n" -eq "$(printf '%s\n' "$listed" | grep -c .)" ] || { fail "every code in $list needs a $k"; bad=1; }
    done
    [ $bad = 0 ] && echo "check-uq-native: $(printf '%s\n' "$live" | grep -c .) codes in $list, all logged"
}
if [ -n "${CODES[uq-diag]:-}" ]; then
    # shellcheck disable=SC2086
    check_codes "${CODES[uq-diag]}" ${SOURCES[uq-diag]:-.}
fi
exit $status
