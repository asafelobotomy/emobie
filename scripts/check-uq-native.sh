#!/usr/bin/env bash
# check-uq-native.sh: checks the uQ kits a repo vendors, as listed in its uq/native.toml.
#
#   scripts/check-uq-native.sh [uq/native.toml]        check (CI)
#   scripts/check-uq-native.sh --sync UQ_DIR [toml]    copy the kits' current files (and this
#                                                      script) from a uQ checkout, then check
#
# For each kit, every listed file's `<kit> X.Y.Z` header (in its first 5 lines) must be the
# pinned version and its contents exactly that release's (the checksums below), so a local edit
# or a half-done update shows up in CI. For uq-diag, `codes` and `sources` also check that the
# problem codes the sources log and the app's list agree (uQ's docs/diagnostics.md).
#
# uq/native.toml (one value per line; lists on one line):
#
#   [uq-theme]
#   version = "1.1.0"
#   files = ["src/uq_theme.rs"]
#
#   [uq-diag]
#   version = "1.0.1"
#   files = ["src/uq_diag.rs"]
#   codes = "uq/diag/myapp.toml"
#   sources = ["src", "qml"]
#
# Kits: uq-theme, uq-diag, uq-consts (uQ's native/) and uq-tokens (uQ's web/). Generated by uQ's
# native/gen-check.sh; copy it unchanged to scripts/check-uq-native.sh. Exit 0 when all match,
# 1 on any mismatch, 2 on bad usage.
set -u
declare -A SUMS=(
